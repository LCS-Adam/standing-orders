# ---------------------------------------------------------------- arg handling
ROLE=""; WRITE=0; FORCE=0
[ $# -gt 0 ] || die "usage: resolve-tier.sh <TIER_FRONTIER_THINK|TIER_FRONTIER_DO|TIER_MID|TIER_SMALL|REVIEWER> [--write-conf [--force]] | --selftest"
while [ $# -gt 0 ]; do
  case "$1" in
    --selftest)   selftest; exit $? ;;
    --write-conf) WRITE=1 ;;
    --force)      FORCE=1 ;;
    -h|--help)    sed -n '5,30p' "$SELF"; exit 0 ;;
    TIER_FRONTIER_THINK|TIER_FRONTIER_DO|TIER_MID|TIER_SMALL|REVIEWER) ROLE="$1" ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done
[ "$FORCE" = "0" ] || [ "$WRITE" = "1" ] || die "--force only means something with --write-conf"
need_jq() { command -v jq >/dev/null 2>&1 || die "required tool not found: jq"; }
need_jq

if [ "$WRITE" = "1" ]; then
  write_conf "$FORCE"
  [ -n "$ROLE" ] || exit 0
fi
[ -n "$ROLE" ] || die "no role given"
resolve "$ROLE"
report "$ROLE"
