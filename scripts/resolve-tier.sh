  has "  ...reported as source=conf" "source=conf" "$ERR"
  rm -f "$tmp/models.auggie.conf"

  echo
  if [ "$F" -gt 0 ]; then printf 'FAILED %d of %d assertions\n' "$F" "$T"; exit 1; fi
